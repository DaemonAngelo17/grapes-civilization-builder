// Helper function to find a matching visual for any option string
export function getOptionVisual(optionText) {
  if (!optionText) return null;
  const lower = optionText.toLowerCase();

  for (const [key, visual] of Object.entries(OPTION_VISUALS)) {
    if (lower.includes(key)) {
      return visual;
    }
  }

  // Generative default historical glyph badges based on keywords
  if (lower.includes('water') || lower.includes('river') || lower.includes('flood')) {
    return {
      isIcon: true,
      iconName: 'Droplets',
      caption: 'Water Feature'
    };
  }
  if (lower.includes('mountain') || lower.includes('cliff') || lower.includes('rock')) {
    return {
      isIcon: true,
      iconName: 'Mountain',
      caption: 'Mountain Terrain'
    };
  }
  if (lower.includes('temple') || lower.includes('god') || lower.includes('priest')) {
    return {
      isIcon: true,
      iconName: 'Flame',
      caption: 'Sacred Temple Rite'
    };
  }
  if (lower.includes('army') || lower.includes('soldier') || lower.includes('phalanx') || lower.includes('shield')) {
    return {
      isIcon: true,
      iconName: 'Shield',
      caption: 'Military Force'
    };
  }
  if (lower.includes('coin') || lower.includes('tax') || lower.includes('trade') || lower.includes('barter')) {
    return {
      isIcon: true,
      iconName: 'Coins',
      caption: 'Economy & Trade'
    };
  }

  return null;
}
