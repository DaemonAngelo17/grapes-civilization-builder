export function getOptionVisual(optionText) {
  if (!optionText || typeof optionText !== 'string') return null;
  const trimmed = optionText.trim();
  const lower = trimmed.toLowerCase();

  // 1. Direct exact match
  if (OPTION_VISUALS_MAP[trimmed]) {
    return OPTION_VISUALS_MAP[trimmed];
  }

  // 2. Direct lowercase key match
  for (const [key, visual] of Object.entries(OPTION_VISUALS_MAP)) {
    if (key.toLowerCase() === lower) {
      return visual;
    }
  }

  // 3. Substring match
  for (const [key, visual] of Object.entries(OPTION_VISUALS_MAP)) {
    const kLower = key.toLowerCase();
    if (lower.includes(kLower) || kLower.includes(lower)) {
      return visual;
    }
  }

  // 4. Default Historical Relic
  return {
    url: 'https://images.unsplash.com/photo-1589829545856-d10d557cf95f?auto=format&fit=crop&w=1000&q=80',
    alt: 'Ancient archaeological stone relic artifact',
    caption: 'Historical Civilization Feature',
    history: 'A foundational component of the ancient world that shaped daily life, government, and cultural survival.'
  };
}
